const savedLocale = localStorage.getItem('bambloo-locale') as Locale | null

export const i18n = createI18n({
  legacy: false,
  locale: savedLocale === 'en-US' ? savedLocale : 'zh-CN',
  fallbackLocale: 'zh-CN',
  messages,
})

export function setLocale(locale: Locale) {
  i18n.global.locale.value = locale
  localStorage.setItem('bambloo-locale', locale)
}

export function toggleLocale() {
  setLocale(i18n.global.locale.value === 'zh-CN' ? 'en-US' : 'zh-CN')
}
